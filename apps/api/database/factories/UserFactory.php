<?php

namespace Database\Factories;

use App\Modules\Identity\Models\User;
use Illuminate\Database\Eloquent\Factories\Factory;
use Illuminate\Support\Facades\Hash;
use Illuminate\Support\Str;

/**
 * @extends Factory<User>
 */
class UserFactory extends Factory
{
    protected $model = User::class;

    protected static ?string $password;

    public function definition(): array
    {
        return [
            'name' => fake()->name(),
            'email' => fake()->unique()->safeEmail(),
            'email_verified_at' => now(),
            'password' => static::$password ??= Hash::make('password123'),
            'remember_token' => Str::random(10),
        ];
    }

    public function unverified(): static
    {
        return $this->state(fn () => ['email_verified_at' => null]);
    }

    public function superAdmin(): static
    {
        return $this->afterCreating(fn (User $user) => $user->forceFill(['platform_role' => User::PLATFORM_SUPER_ADMIN])->save());
    }

    public function supportAdmin(): static
    {
        return $this->afterCreating(fn (User $user) => $user->forceFill(['platform_role' => User::PLATFORM_SUPPORT_ADMIN])->save());
    }
}
